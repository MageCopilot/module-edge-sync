<?php
declare(strict_types=1);

namespace MageCopilot\EdgeSync\Service\Feed;

use MageCopilot\EdgeSync\Model\Config;
use Magento\Framework\App\Filesystem\DirectoryList;
use Magento\Framework\Escaper;
use Magento\Framework\Filesystem;
use Magento\Framework\Filesystem\Directory\WriteInterface;
use Magento\Framework\UrlInterface;
use Magento\Store\Model\StoreManagerInterface;
use Psr\Log\LoggerInterface;

/**
 * Service to export product feeds from Typesense Memory Grid with constant memory usage.
 */
class TypesenseFeedExporterService
{
    public const CHANNEL_GOOGLE = 'google';
    public const CHANNEL_META = 'meta';
    public const CHANNEL_TIKTOK = 'tiktok';

    public const SUPPORTED_CHANNELS = [
        self::CHANNEL_GOOGLE,
        self::CHANNEL_META,
        self::CHANNEL_TIKTOK
    ];

    /**
     * @var WriteInterface
     */
    private WriteInterface $mediaDirectory;

    /**
     * @param Config $config
     * @param Filesystem $filesystem
     * @param StoreManagerInterface $storeManager
     * @param Escaper $escaper
     * @param LoggerInterface $logger
     */
    public function __construct(
        private Config $config,
        private Filesystem $filesystem,
        private StoreManagerInterface $storeManager,
        private Escaper $escaper,
        private LoggerInterface $logger
    ) {
        $this->mediaDirectory = $this->filesystem->getDirectoryWrite(DirectoryList::MEDIA);
    }

    /**
     * Export catalog feed from Typesense memory cluster to disk with O(1) memory usage.
     *
     * @param string $channel
     * @param string|null $storeCode
     * @return array{
     *   channel: string,
     *   file: string,
     *   relative_path: string,
     *   count: int,
     *   execution_time: float,
     *   file_size: int
     * }
     * @throws \InvalidArgumentException
     * @throws \RuntimeException
     */
    public function export(string $channel, ?string $storeCode = null): array
    {
        $normalizedChannel = strtolower(trim($channel));
        if (!in_array($normalizedChannel, self::SUPPORTED_CHANNELS, true)) {
            $supportedList = implode(', ', self::SUPPORTED_CHANNELS);
            throw new \InvalidArgumentException(
                sprintf('Unsupported feed channel "%s". Supported channels: %s', $channel, $supportedList)
            );
        }

        $startTime = microtime(true);
        $this->mediaDirectory->create('feeds');

        $filename = match ($normalizedChannel) {
            self::CHANNEL_TIKTOK => 'tiktok.csv',
            self::CHANNEL_META => 'meta.xml',
            default => 'google.xml'
        };

        $absolutePath = $this->mediaDirectory->getAbsolutePath('feeds/' . $filename);
        $fileHandle = fopen($absolutePath, 'w');
        if ($fileHandle === false) {
            throw new \RuntimeException(sprintf('Cannot open destination feed file: %s', $absolutePath));
        }

        $store = $storeCode !== null
            ? $this->storeManager->getStore($storeCode)
            : $this->storeManager->getDefaultStoreView();

        $storeModel = $store instanceof \Magento\Store\Model\Store ? $store : null;
        $storeName = (string) ($store ? $store->getName() : 'MageCopilot Store');
        $baseUrl = (string) ($storeModel
            ? $storeModel->getBaseUrl(UrlInterface::URL_TYPE_WEB)
            : 'https://store.magecopilot.com/');
        $currencyCode = (string) ($storeModel ? $storeModel->getCurrentCurrencyCode() : 'USD');

        $isCsv = ($normalizedChannel === self::CHANNEL_TIKTOK);

        if ($isCsv) {
            fwrite($fileHandle, "sku_id,title,description,availability,condition,price,link,image_link,brand\n");
        } else {
            $xmlHeader = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n"
                . "<rss xmlns:g=\"http://base.google.com/ns/1.0\" version=\"2.0\">\n"
                . "  <channel>\n"
                . "    <title>" . $this->escaper->escapeHtml($storeName) . " Product Feed</title>\n"
                . "    <link>" . $this->escaper->escapeHtml($baseUrl) . "</link>\n"
                . "    <description>Product feed generated by MageCopilot Memory Grid Engine</description>\n";
            fwrite($fileHandle, $xmlHeader);
        }

        $exportedCount = 0;
        $lineBuffer = '';

        $url = rtrim($this->config->getHost(), '/') . '/collections/'
            . urlencode($this->config->getCollectionName()) . '/documents/export';

        $ch = curl_init($url);
        curl_setopt($ch, CURLOPT_HTTPHEADER, [
            'X-TYPESENSE-API-KEY: ' . $this->config->getApiKey(),
            'Content-Type: application/json'
        ]);
        curl_setopt($ch, CURLOPT_TIMEOUT, 300);
        curl_setopt($ch, CURLOPT_CONNECTTIMEOUT, 10);

        curl_setopt(
            $ch,
            CURLOPT_WRITEFUNCTION,
            function (
                $curlHandle,
                string $chunk
            ) use (
                $fileHandle,
                $isCsv,
                $baseUrl,
                $currencyCode,
                $storeName,
                &$lineBuffer,
                &$exportedCount
            ): int {
                $lineBuffer .= $chunk;
                while (($newlinePos = strpos($lineBuffer, "\n")) !== false) {
                    $line = trim(substr($lineBuffer, 0, $newlinePos));
                    $lineBuffer = substr($lineBuffer, $newlinePos + 1);

                    if ($line === '') {
                        continue;
                    }

                    $doc = json_decode($line, true);
                    if (!is_array($doc) || empty($doc['sku'])) {
                        continue;
                    }

                    $rendered = $isCsv
                        ? $this->renderCsvRow($doc, $baseUrl, $currencyCode, $storeName)
                        : $this->renderXmlItem($doc, $baseUrl, $currencyCode, $storeName);

                    fwrite($fileHandle, $rendered);
                    $exportedCount++;
                }
                return strlen($chunk);
            }
        );

        $execResult = curl_exec($ch);
        $httpCode = curl_getinfo($ch, CURLINFO_HTTP_CODE);
        $curlError = curl_error($ch);

        if (trim($lineBuffer) !== '') {
            $doc = json_decode(trim($lineBuffer), true);
            if (is_array($doc) && !empty($doc['sku'])) {
                $rendered = $isCsv
                    ? $this->renderCsvRow($doc, $baseUrl, $currencyCode, $storeName)
                    : $this->renderXmlItem($doc, $baseUrl, $currencyCode, $storeName);
                fwrite($fileHandle, $rendered);
                $exportedCount++;
            }
        }

        if (!$isCsv) {
            $xmlFooter = "  </channel>\n</rss>\n";
            fwrite($fileHandle, $xmlFooter);
        }

        fclose($fileHandle);

        if ($execResult === false || $httpCode < 200 || $httpCode >= 300) {
            $this->logger->error(sprintf(
                '[MageCopilot_EdgeSync] Feed export HTTP error: code=%d error=%s',
                $httpCode,
                $curlError
            ));
            throw new \RuntimeException(sprintf(
                'Typesense feed streaming failed: HTTP %d %s',
                $httpCode,
                $curlError
            ));
        }

        $executionTime = round(microtime(true) - $startTime, 3);
        $fileSize = (int) (filesize($absolutePath) ?: 0);

        $this->logger->info(sprintf(
            '[MageCopilot_EdgeSync] Feed export finished: channel=%s count=%d size=%d bytes time=%.3fs',
            $normalizedChannel,
            $exportedCount,
            $fileSize,
            $executionTime
        ));

        return [
            'channel' => $normalizedChannel,
            'file' => $absolutePath,
            'relative_path' => 'pub/media/feeds/' . $filename,
            'count' => $exportedCount,
            'execution_time' => $executionTime,
            'file_size' => $fileSize
        ];
    }

    /**
     * Render XML item element for Google and Meta catalogs.
     *
     * @param array<string, mixed> $doc
     * @param string $baseUrl
     * @param string $currencyCode
     * @param string $storeName
     * @return string
     */
    private function renderXmlItem(
        array $doc,
        string $baseUrl,
        string $currencyCode,
        string $storeName
    ): string {
        $sku = $this->escaper->escapeHtml((string) ($doc['sku'] ?? ''));
        $title = $this->escaper->escapeHtml((string) ($doc['name'] ?? ''));
        $rawDesc = strip_tags((string) ($doc['description'] ?? $doc['name'] ?? ''));
        $description = $this->escaper->escapeHtml(mb_substr($rawDesc, 0, 1000));

        $slug = rawurlencode((string) ($doc['url_key'] ?? $doc['sku'] ?? ''));
        $link = rtrim($baseUrl, '/') . '/p/' . $slug;
        $placeholderUrl = rtrim($baseUrl, '/') . '/images/placeholder.svg';
        $imageLink = $this->escaper->escapeHtml((string) ($doc['image_url'] ?? $placeholderUrl));

        $inStock = !empty($doc['is_in_stock']) || !empty($doc['in_stock']);
        $availability = $inStock ? 'in_stock' : 'out_of_stock';

        $price = number_format((float) ($doc['price'] ?? 0), 2, '.', '') . ' ' . $currencyCode;
        $brand = $this->escaper->escapeHtml((string) ($doc['brand'] ?? $storeName));

        return "    <item>\n"
            . "      <g:id>{$sku}</g:id>\n"
            . "      <g:title>{$title}</g:title>\n"
            . "      <g:description>{$description}</g:description>\n"
            . "      <g:link>{$link}</g:link>\n"
            . "      <g:image_link>{$imageLink}</g:image_link>\n"
            . "      <g:condition>new</g:condition>\n"
            . "      <g:availability>{$availability}</g:availability>\n"
            . "      <g:price>{$price}</g:price>\n"
            . "      <g:brand>{$brand}</g:brand>\n"
            . "    </item>\n";
    }

    /**
     * Render CSV row for TikTok catalog.
     *
     * @param array<string, mixed> $doc
     * @param string $baseUrl
     * @param string $currencyCode
     * @param string $storeName
     * @return string
     */
    private function renderCsvRow(
        array $doc,
        string $baseUrl,
        string $currencyCode,
        string $storeName
    ): string {
        $sku = (string) ($doc['sku'] ?? '');
        $title = '"' . str_replace('"', '""', (string) ($doc['name'] ?? '')) . '"';
        $rawDesc = strip_tags((string) ($doc['description'] ?? $doc['name'] ?? ''));
        $desc = '"' . str_replace('"', '""', mb_substr($rawDesc, 0, 500)) . '"';

        $inStock = !empty($doc['is_in_stock']) || !empty($doc['in_stock']);
        $availability = $inStock ? 'in stock' : 'out of stock';

        $price = number_format((float) ($doc['price'] ?? 0), 2, '.', '') . ' ' . $currencyCode;
        $slug = rawurlencode((string) ($doc['url_key'] ?? $doc['sku'] ?? ''));
        $link = rtrim($baseUrl, '/') . '/p/' . $slug;
        $image = (string) ($doc['image_url'] ?? rtrim($baseUrl, '/') . '/images/placeholder.svg');
        $brand = '"' . str_replace('"', '""', (string) ($doc['brand'] ?? $storeName)) . '"';

        return implode(',', [$sku, $title, $desc, $availability, 'new', $price, $link, $image, $brand]) . "\n";
    }
}
